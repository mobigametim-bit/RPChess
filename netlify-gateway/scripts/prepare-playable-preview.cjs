/* Local-first playable acceptance build. Core HTML, JS, CSS and Tournament
 * art must not depend on third-party GitHub Pages rewrites on Russian networks.
 * Only nonessential large art/audio and other unneeded modes use the existing
 * /play/* CDN fallback; never copy raw 700+ MiB assets wholesale.
 */
const fs=require('node:fs');
const path=require('node:path');
const repo=path.resolve(__dirname,'..','..');
const game=path.join(repo,'game');
const dest=path.join(repo,'netlify-gateway','public','play');
fs.rmSync(dest,{recursive:true,force:true});
let count=0,bytes=0;
const one=(relative,target=relative)=>{
 const source=path.join(game,relative),output=path.join(dest,target);
 if(!fs.existsSync(source))throw Error('Missing playable source: '+relative);
 fs.mkdirSync(path.dirname(output),{recursive:true});
 fs.copyFileSync(source,output);
 bytes+=fs.statSync(source).size;count++;
};
const tree=(relative)=>{
 const root=path.join(game,relative);
 if(!fs.existsSync(root))throw Error('Missing playable directory: '+relative);
 function visit(dir){
  for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
   const file=path.join(dir,entry.name);
   if(entry.isDirectory())visit(file);
   else if(entry.isFile())one(path.relative(game,file));
  }
 }
 visit(root);
};
one('index.html');
for(const folder of ['js','css','fonts','localization','generated_assets',
 'assets/ui','assets/boards','assets/arena','assets/pieces/fantasy'])
 tree(folder);
// Tournament supports all fourteen race skins. Only 2D board figures belong
// here; original 4K race backgrounds and event panoramas stay excluded.
const races=path.join(game,'assets','races');
for(const name of fs.readdirSync(races)){
 const prefix='assets/races/'+name+'/pieces/board';
 if(fs.existsSync(path.join(game,prefix)))tree(prefix);
}
// Tournament player identity shows the selected King portrait and rating icon.
const kings=path.join(game,'assets','kings');
for(const name of fs.readdirSync(kings)){
 const portrait='assets/kings/'+name+'/portrait.webp';
 if(fs.existsSync(path.join(game,portrait)))one(portrait);
}
one('assets/doctrines/royal_court/emblem.png');
// This catalogue is generated by the normal 500 MiB build; generate a matching
// lightweight copy without downloading audio or shipping noncommercial tracks.
const catalog=path.join(dest,'js','music-catalog.mjs');
if(!fs.existsSync(catalog)){
 const entries=[];
 const musicRoot=path.join(game,'music');
 function visit(dir){
  if(!fs.existsSync(dir))return;
  for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
   const file=path.join(dir,entry.name);
   if(entry.isDirectory())visit(file);
   else if(entry.isFile()&&/\.(mp3|ogg|wav)$/i.test(entry.name)){
    const relative=path.relative(musicRoot,file).split(path.sep).join('/');
    if(relative!=='epic_music3.mp3')entries.push('music/'+relative);
   }
  }
 }
 visit(musicRoot);
 fs.writeFileSync(catalog,'const MUSIC_TRACKS=Object.freeze('+JSON.stringify(entries.sort())+');\nexport {MUSIC_TRACKS};\n');
 count++;bytes+=fs.statSync(catalog).size;
}
const page=fs.readFileSync(path.join(dest,'index.html'),'utf8');
if(!page.includes('data-tournament-open')||!page.includes('rpchess-profile-api'))
 throw Error('Incomplete preview homepage');
const required=['js/tournament-app.mjs','js/api-route.mjs','js/reboot-foundation.mjs',
 'js/profile-client.mjs','js/screen-loading.mjs','js/music-catalog.mjs',
 'css/tournament-v4.css','generated_assets/logo_ru.png',
 'assets/races/humans/pieces/board/white/king.png'];
for(const relative of required){
 if(!fs.existsSync(path.join(dest,relative)))throw Error('Missing local Tournament asset: '+relative);
}
console.log('Self-contained Tournament preview core: '+count+' files / '+(bytes/1048576).toFixed(1)+' MiB; large non-Tournament art uses CDN fallback.');
