const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'game/js/generated/iron-marches-runtime.bundle.js');
const shimRoot = path.join(root, 'src/browser/node-shims');

const nodeShimPlugin = {
  name: 'rpchess-node-shims',
  setup(build) {
    build.onResolve({ filter: /^(?:node:)?fs$/ }, () => ({ path: path.join(shimRoot, 'fs.cjs') }));
    build.onResolve({ filter: /^(?:node:)?path$/ }, () => ({ path: path.join(shimRoot, 'path.cjs') }));
    build.onResolve({ filter: /^(?:node:)?crypto$/ }, () => ({ path: path.join(shimRoot, 'crypto.cjs') }));
  }
};

async function buildBrowserRuntime() {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  await esbuild.build({
    entryPoints: [path.join(root, 'src/browser/iron-marches-browser-entry.cjs')],
    outfile: output,
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: 'RPChessRuntime',
    target: ['es2020'],
    sourcemap: false,
    minify: false,
    legalComments: 'none',
    charset: 'utf8',
    plugins: [nodeShimPlugin],
    banner: { js: '/* Generated by scripts/build-browser-runtime.cjs. Do not edit manually. */' }
  });

  const bytes = fs.statSync(output).size;
  if (bytes < 1000) throw new Error(`browser runtime bundle is unexpectedly small: ${bytes}`);
  console.log(`Prepared browser production runtime: ${path.relative(root, output)} (${bytes} bytes)`);
  return output;
}

if (require.main === module) {
  buildBrowserRuntime().catch((error) => {
    console.error(error.stack || error);
    process.exitCode = 1;
  });
}

module.exports = buildBrowserRuntime;
