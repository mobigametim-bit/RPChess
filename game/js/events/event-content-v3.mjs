function applyEventContentV3(event) {
  const authored = EVENT_CONTENT_V3[event?.id];
  if (!event || !authored) return event;
  return {
    ...event,
    title: authored.title,
    story: authored.storyParagraphs.join('\n\n'),
    storyParagraphs: [...authored.storyParagraphs],
    kingReaction: authored.kingReaction || null,
    choices: (event.choices || []).map((choice) => {
      const override = authored.choices?.[choice.id];
      if (!override) return choice;
      return {
        ...choice,
        action: override.action,
        heroReaction: override.heroReaction ? { ...override.heroReaction } : null
      };
    })
  };
}

function personalizedHeroName(hero) {
  if (!hero || typeof hero.name !== 'string' || !hero.name.trim()) return '';
  const id = String(hero.id || '');
  const portrait = String(hero.portrait || '');
  return id.startsWith('hero.') || portrait.includes('/heroes/') ? hero.name.trim() : '';
}

function formatHeroReaction(reaction, hero = null) {
  if (!reaction?.text) return '';
  const role = String(reaction.role || '').toLowerCase();
  const speaker = personalizedHeroName(hero) || ROLE_FALLBACK[role] || 'Ваш герой';
  return String(reaction.text).replace(/\{(?:pawn|knight|bishop|rook|queen)Name\}/g, speaker);
}

export { EVENT_CONTENT_V3, ROLE_FALLBACK, applyEventContentV3, formatHeroReaction };
